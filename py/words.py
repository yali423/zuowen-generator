_RICH_RE = re.compile("|".join(sorted(set(RICH_WORDS), key=len, reverse=True)))


def richness(sent):
    """一句话的"词级分"：出现几个好词。用来做分档偏好，不改原句。"""
    if not sent:
        return 0
    return len(_RICH_RE.findall(sent))


def upgrade(text, rng, p=0.7):
    """高档：把朴素词换成好词（低概率，避免句句用力）。"""
    for a, b in SAFE_SWAP:
        if a in text and rng.random() < p:
            # "最特别"不能换成"最格外"（病句）
            text = re.sub("(?<!最)" + re.escape(a), b, text, count=1)
    return text


def downgrade(text, rng, p=0.85):
    """低档：把好词换回朴素说法，让语言更像普通孩子。"""
    for a, b in DOWN_SWAP:
        if a in text and rng.random() < p:
            text = text.replace(a, b, 1)
    return text
